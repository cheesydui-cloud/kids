func clashHy2(uri, name string) (string, bool) {
	u, err := url.Parse(uri)
	if err != nil {
		return "", false
	}
	host := u.Hostname()
	port, _ := strconv.Atoi(u.Port())
	if host == "" || port < 1 {
		return "", false
	}
	auth := ""
	if u.User != nil {
		auth = u.User.Username()
		if p, ok := u.User.Password(); ok && p != "" {
			auth = p
		}
	}
	q := u.Query()
	L := []string{
		fmt.Sprintf("- name: %s", yamlQuoted(name)),
		"  type: hysteria2",
		fmt.Sprintf("  server: %s", yamlScalar(host)),
		fmt.Sprintf("  port: %d", port),
	}
	if auth != "" {
		L = append(L, "  password: "+yamlQuoted(auth))
	}
	if sni := q.Get("sni"); sni != "" {
		L = append(L, "  sni: "+yamlScalar(sni))
	}
	if q.Get("insecure") == "1" {
		L = append(L, "  skip-cert-verify: true")
	}
	if q.Get("obfs") == "salamander" && q.Get("obfs-password") != "" {
		L = append(L, "  obfs: salamander")
		L = append(L, "  obfs-password: "+yamlQuoted(q.Get("obfs-password")))
	}
	return strings.Join(L, "\n"), true
}

func appendTransport(L []string, netw string, q url.Values) []string {
	if netw == "ws" {
		L = append(L, "  ws-opts:")
		if path := q.Get("path"); path != "" {
			L = append(L, "    path: "+yamlQuoted(path))
		}
		if host := q.Get("host"); host != "" {
			L = append(L, "    headers:", "      Host: "+yamlScalar(host))
		}
	} else if netw == "grpc" {
		svc := firstNonEmpty(q.Get("serviceName"), q.Get("service_name"))
		if svc != "" {
			L = append(L, "  grpc-opts:", "    grpc-service-name: "+yamlQuoted(svc))
		}
	}
	return L
}

func parseQuery(raw string) map[string]string {
	m := map[string]string{}
	for _, p := range strings.Split(raw, "&") {
		if p == "" {
			continue
		}
		k, v, _ := strings.Cut(p, "=")
		if k == "" {
			continue
		}
		dk, _ := url.QueryUnescape(k)
		dv, _ := url.QueryUnescape(v)
		m[dk] = dv
	}
	return m
}

func splitHP(s string) (string, int, bool) {
	s = strings.TrimSpace(s)
	if s == "" {
		return "", 0, false
	}
	host, portStr, err := net.SplitHostPort(s)
	if err != nil {
		return "", 0, false
	}
	port, err := strconv.Atoi(portStr)
	if err != nil || host == "" || port < 1 || port > 65535 {
		return "", 0, false
	}
	return host, port, true
}

func yamlQuoted(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, `"`, `\"`)
	return `"` + s + `"`
}

func yamlScalar(s string) string {
	if s == "" || strings.ContainsAny(s, ":#{}[],&*?|>!%@`'\" \t") {
		return yamlQuoted(s)
	}
	return s
}

func firstNonEmpty(vals ...string) string {
	for _, v := range vals {
		if v != "" {
			return v
		}
	}
	return ""
}

// EncodeURISubscription is the standard client subscription body: a
// newline-joined URI list, then standard base64 (with padding).
func EncodeURISubscription(uris []string) string {
	var lines []string
	for _, u := range uris {
		u = strings.TrimSpace(u)
		if u != "" {
			lines = append(lines, u)
		}
	}
	raw := strings.Join(lines, "\n")
	if raw != "" {
		raw += "\n"
	}
	return base64.StdEncoding.EncodeToString([]byte(raw))
}
